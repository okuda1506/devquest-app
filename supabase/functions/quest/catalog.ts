export const tasks = entries.map((entry, index) => {
    const id = 'DEV-' + (101 + index);
    return {
        ...entry,
        id,
        branch: 'task/' + id,
        requester: team[entry.author],
        chapter: Math.floor(index / 3),
        available: index < 4,
        previous: index > 0 ? 'DEV-' + (100 + index) : null
    };
});
export type Task = (typeof tasks)[number];
export const getTask = (id: string) => tasks.find((task) => task.id === id);
export const branchCommands = (task: Task) =>
    ['git switch main', 'git pull --ff-only origin main', 'git switch -c ' + task.branch].join('\n');
